"""Generate static/dark.css from the light stylesheets.

    python tools/build_dark_css.py           # rewrite static/dark.css
    python tools/build_dark_css.py --check   # exit 1 if it is out of date

The light theme hard-codes its colours across ~100 KB of CSS. Rather than maintain a
second copy by hand, every colour declaration is re-emitted under
``html[data-theme="dark"]`` with its lightness inverted, keeping its hue. The light
stylesheets stay the single source, and tests/test_server.py fails if this file drifts.
"""

from __future__ import annotations

import argparse
import colorsys
import re
import sys
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("styles.css", "dashboard.css", "readability.css")
TARGET = ROOT / "static" / "dark.css"
THEME = 'html[data-theme="dark"]'
COLOUR = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\b(?:white|black)\b")
COLOUR_PROPERTY = re.compile(r"^(?:color|background(?:-color|-image)?|border(?:-(?:top|right|bottom|left|block|inline))*(?:-color)?"
                             r"|outline(?:-color)?|box-shadow|text-shadow|fill|stroke|caret-color|accent-color|text-decoration(?:-color)?|--[\w-]+)$")
#: Darkest background and lightest text the inversion may produce.
DARKEST, LIGHTEST = 0.11, 0.91
HEADER = f"""/* Generated by tools/build_dark_css.py from {", ".join(SOURCES)}. Do not edit by hand. */
{THEME}{{color-scheme:dark}}
{THEME} .process-schematic rect{{fill:#22303d}}
{THEME} .process-schematic marker path{{fill:#a9bac8}}
{THEME} .process-schematic svg g[stroke]{{stroke:#a9bac8}}
"""


def parse_colour(token: str) -> tuple[float, float, float, float]:
    if token == "white":
        return 1.0, 1.0, 1.0, 1.0
    if token == "black":
        return 0.0, 0.0, 0.0, 1.0
    if token.startswith("#"):
        digits = token[1:]
        if len(digits) in (3, 4):
            digits = "".join(c * 2 for c in digits)
        values = [int(digits[i:i + 2], 16) / 255 for i in range(0, len(digits), 2)]
        return values[0], values[1], values[2], values[3] if len(values) == 4 else 1.0
    parts = [float(p.rstrip("%")) for p in re.split(r"[,\s/]+", token[token.index("(") + 1:-1].strip())]
    return parts[0] / 255, parts[1] / 255, parts[2] / 255, parts[3] if len(parts) == 4 else 1.0


def invert(token: str) -> str:
    red, green, blue, alpha = parse_colour(token)
    hue, lightness, saturation = colorsys.rgb_to_hls(red, green, blue)
    lightness = DARKEST + (1 - lightness) * (LIGHTEST - DARKEST)
    red, green, blue = colorsys.hls_to_rgb(hue, lightness, saturation * 0.85)
    channels = [round(value * 255) for value in (red, green, blue)]
    return f"#{channels[0]:02x}{channels[1]:02x}{channels[2]:02x}" if alpha == 1.0 else f"rgba({channels[0]},{channels[1]},{channels[2]},{alpha:g})"


def shadow(token: str) -> str:
    return f"rgba(0,0,0,{min(1.0, parse_colour(token)[3] * 2.5):g})"


def _invert_match(match: re.Match[str]) -> str:
    return invert(match.group())


def _shadow_match(match: re.Match[str]) -> str:
    return shadow(match.group())


def declarations(body: str) -> list[str]:
    kept = []
    for declaration in re.split(r";(?![^(]*\))", body):
        name, separator, value = declaration.partition(":")
        name = name.strip()
        if not separator or not COLOUR_PROPERTY.match(name) or not COLOUR.search(value):
            continue
        swap = _shadow_match if name in ("box-shadow", "text-shadow") else _invert_match
        kept.append(f"{name}:{COLOUR.sub(swap, value.strip())}")
    return kept


def split_selectors(prelude: str) -> list[str]:
    selectors, depth, current = [], 0, ""
    for character in prelude:
        depth += (character in "([") - (character in ")]")
        if character == "," and depth == 0:
            selectors.append(current)
            current = ""
        else:
            current += character
    return [*selectors, current]


def themed(selector: str) -> str:
    selector = " ".join(selector.split())
    if selector in (":root", "html"):
        return THEME
    if selector.startswith(":root"):
        return THEME + selector[5:]
    return f"{THEME} {selector}"


def blocks(text: str) -> Iterator[tuple[str, str]]:
    """Yield top-level ``(prelude, body)`` pairs of a stylesheet."""
    depth, start, prelude = 0, 0, ""
    for index, character in enumerate(text):
        if character == "{":
            if depth == 0:
                prelude, start = text[start:index], index + 1
            depth += 1
        elif character == "}":
            depth -= 1
            if depth == 0:
                yield prelude.strip(), text[start:index]
                start = index + 1


def convert(text: str) -> list[str]:
    output = []
    for prelude, body in blocks(text):
        if prelude.startswith("@"):
            if prelude.startswith("@media") and not re.search(r"forced-colors|print", prelude):
                inner = convert(body)
                if inner:
                    output.append(f"{prelude}{{{''.join(inner)}}}")
            continue
        kept = declarations(body)
        if kept:
            output.append(f"{','.join(themed(s) for s in split_selectors(prelude))}{{{';'.join(kept)}}}\n")
    return output


def generate() -> str:
    parts = [HEADER]
    for name in SOURCES:
        text = re.sub(r"/\*.*?\*/", "", (ROOT / "static" / name).read_text(encoding="utf-8"), flags=re.S)
        parts.extend(convert(text))
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report whether static/dark.css is current")
    css = generate()
    if parser.parse_args().check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current.replace("\r\n", "\n") != css:
            print("static/dark.css is out of date. Run: python tools/build_dark_css.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(css, encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(ROOT).as_posix()} ({len(css):,} characters).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
